#!/usr/bin/env bash
# ============================================================================
#  Vanks OS — звуки Delta (delta/shell/sounds/*.ogg), синтез ffmpeg.
#
#      tools/gen-sounds.sh
#
#  Мягкие «стеклянные» тона: синус с тихой второй гармоникой и быстрым
#  затуханием, пентатоника от до. Файлы маленькие (ogg vorbis, моно 48 кГц),
#  их кладут в репозиторий — пересобирать нужно только после правки здесь.
# ============================================================================
set -euo pipefail

PROJECT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="${PROJECT_DIR}/delta/shell/sounds"
mkdir -p "${OUT}"

# нота: частота, начало (с), затухание, громкость
note() { printf '(gt(t,%s)*%s*(sin(2*PI*%s*(t-%s))+0.18*sin(4*PI*%s*(t-%s)))*exp(-%s*(t-%s))*(1-exp(-260*(t-%s))))' \
    "$2" "$4" "$1" "$2" "$1" "$2" "$3" "$2" "$2"; }

gen() {  # имя, длительность, выражение, [доп. фильтр]
    ffmpeg -v error -nostdin -y -f lavfi -i "aevalsrc='$3':s=48000:d=$2" \
        -af "${4:-anull},afade=t=out:st=$(awk -v d="$2" 'BEGIN{printf "%.3f", d-0.08}'):d=0.08,aformat=channel_layouts=mono" \
        -c:a libvorbis -q:a 4 "${OUT}/$1.ogg"
    printf '  %s.ogg\n' "$1"
}

C5=523.25; D5=587.33; E5=659.26; G5=783.99; A5=880.00; C6=1046.50; E6=1318.51; G4=392.00

echo "звуки → ${OUT}"
# первая настройка: стекается — восходящее арпеджио
gen oobe-hello 2.4 "$(note $C5 0 2.6 0.30)+$(note $E5 0.13 2.4 0.27)+$(note $G5 0.26 2.2 0.25)+$(note $C6 0.39 2.0 0.22)+$(note $E6 0.52 1.8 0.12)" \
    "aecho=0.8:0.6:90|170:0.25|0.15"
# переход на следующий шаг — лёгкий щипок
gen oobe-step 0.35 "$(note $G5 0 14 0.32)+$(note $C6 0.045 16 0.16)"
# назад — тот же щипок вниз
gen oobe-back 0.35 "$(note $C6 0 14 0.26)+$(note $G5 0.045 16 0.16)"
# выбор варианта (тема, обои, язык)
gen oobe-select 0.4 "$(note $E5 0 11 0.28)+$(note $A5 0.06 12 0.22)"
# удержание «Начать»: мягкий нарастающий гул (1.5 с), обрывается, если отпустить
gen oobe-hold 1.6 "0.22*(sin(2*PI*(196*t+150*t*t))+0.35*sin(4*PI*(196*t+150*t*t)))*min(1,t*3)*(0.55+0.45*t/1.6)" \
    "lowpass=f=2400"
# готово: аккорд распускается
gen oobe-done 3.2 "$(note $C5 0 1.4 0.24)+$(note $E5 0.03 1.3 0.22)+$(note $G5 0.06 1.2 0.2)+$(note $C6 0.09 1.1 0.18)+$(note $E6 0.25 1.5 0.10)+$(note $G4 0 1.2 0.18)" \
    "aecho=0.8:0.7:120|240|380:0.3|0.2|0.12"

# система
# меню и капли из дока — «бульк» с подъёмом тона
gen pop 0.22 "0.32*sin(2*PI*(380*t+1700*t*t))*exp(-22*t)*(1-exp(-300*t))"
# смена рабочего стола — короткий стеклянный тик
gen workspace 0.3 "$(note $D5 0 18 0.2)+$(note $A5 0.03 20 0.12)"
# остров раскрылся (музыка, сообщение)
gen island 0.6 "$(note $G5 0 7 0.2)+$(note $D5 0.07 7 0.16)+$(note $G5 0.14 6 0.12)"
# окно свернулось в док — «вжух» вниз
gen swoosh 0.4 "0.22*sin(2*PI*(900*t-900*t*t))*exp(-9*t)*(1-exp(-120*t))" "lowpass=f=3000"
# виджет поставлен на место — мягкий «тук»
gen drop 0.25 "0.4*sin(2*PI*(170*t-120*t*t))*exp(-26*t)*(1-exp(-500*t))"
# разблокировка — два восходящих тона
gen unlock 0.7 "$(note $E5 0 8 0.22)+$(note $C6 0.09 7 0.2)"
# окно у края — подсветка зоны: короткий стеклянный «вжик» вверх
gen snap-in 0.32 "0.16*sin(2*PI*(620*t+900*t*t))*exp(-14*t)*(1-exp(-400*t))+$(note $A5 0.02 16 0.08)" "lowpass=f=5000"
# окно прилипло к краю — мягкий «тук» и звон
gen snap 0.5 "0.34*sin(2*PI*(210*t-160*t*t))*exp(-24*t)*(1-exp(-500*t))+$(note $E6 0.03 12 0.1)"
# окно приложений открылось — воздушный аккорд снизу вверх
gen launcher 0.7 "$(note $C5 0 9 0.12)+$(note $G5 0.04 9 0.1)+$(note $C6 0.08 8 0.08)+0.05*sin(2*PI*(300*t+700*t*t))*exp(-8*t)" "aecho=0.8:0.5:60:0.2"
# буква или строка проявилась — очень тихий стеклянный тик
gen tick 0.09 "0.2*sin(2*PI*2200*t)*exp(-70*t)*(1-exp(-900*t))+0.08*sin(2*PI*3300*t)*exp(-90*t)"
# первая настройка: искры вокруг заголовка
gen sparkle 0.9 "$(note $E6 0 9 0.08)+$(note 1567.98 0.07 10 0.07)+$(note 2093.0 0.14 11 0.06)+$(note 2637.0 0.21 12 0.05)" "aecho=0.8:0.6:80:0.3"
echo "готово"
