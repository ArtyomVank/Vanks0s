def dots(spec):
    """Центры точек знака (x, y) и ширина в клетках."""
    acc, main, desc = [], [], []
    for row in spec.split():
        if row.startswith("^"):
            acc.append(row[1:])
        elif row.startswith(","):
            desc.append(row[1:])
        else:
            main.append(row)
    if len(main) not in (5, 7):
        raise ValueError(f"знак {spec!r}: {len(main)} рядов")
    width = max(len(r) for r in acc + main + desc)
    top = 7 - len(main)             # строчные начинаются с третьего ряда
    pts = []

    def put(row, y):
        for c, ch in enumerate(row):
            if ch == "#":
                pts.append((CELL + c * CELL, y))

    for i, row in enumerate(main):
        put(row, (6 - (top + i)) * CELL + CELL // 2)
    for row in acc:                  # над прописной — через пустой ряд
        put(row, 8 * CELL + CELL // 2)
    for i, row in enumerate(desc):
        put(row, -(i * CELL) - CELL // 2)
    return pts, width


def circle(cx, cy):
    """Точка — окружность из 8 квадратичных дуг, по часовой стрелке."""
    out, far = [], DOT / math.cos(math.pi / 8)
    for k in range(8):
        a = -k * math.pi / 4
        out.append((round(cx + DOT * math.cos(a)), round(cy + DOT * math.sin(a)), True))
        b = a - math.pi / 8
        out.append((round(cx + far * math.cos(b)), round(cy + far * math.sin(b)), False))
    return out


def glyph(pts):
    if not pts:
        return b"", (0, 0, 0, 0), 0
    contours = [circle(x, y) for x, y in pts]
    allp = [p for c in contours for p in c]
    xs, ys = [p[0] for p in allp], [p[1] for p in allp]
    box = (min(xs), min(ys), max(xs), max(ys))
    data = struct.pack(">hhhhh", len(contours), *box)
    n = 0
    for c in contours:
        n += len(c)
        data += struct.pack(">H", n - 1)
    data += struct.pack(">H", 0)                      # без инструкций
    data += bytes(1 if on else 0 for _, _, on in allp)
    px = py = 0
    xd = yd = b""
    for x, y, _ in allp:
        xd += struct.pack(">h", x - px)
        yd += struct.pack(">h", y - py)
        px, py = x, y
    data += xd + yd
    while len(data) % 4:
        data += b"\0"
    return data, box, len(allp)


def checksum(b):
    b += b"\0" * (-len(b) % 4)
    return sum(struct.unpack(f">{len(b) // 4}I", b)) & 0xFFFFFFFF


def build():
    chars = sorted(G, key=ord)
    # .notdef — рамка из точек
    notdef = [(CELL + c * CELL, (6 - r) * CELL + CELL // 2)
              for r in range(7) for c in range(4) if r in (0, 6) or c in (0, 3)]
    glyphs = [(notdef, 4)] + [dots(G[ch]) for ch in chars]

    glyf, loca, hmtx = b"", [0], b""
    boxes, maxpts, maxcont, adv_max = [], 0, 0, 0
    for pts, w in glyphs:
        data, box, npts = glyph(pts)
        glyf += data
        loca.append(len(glyf))
        adv = (w + 1) * CELL
        adv_max = max(adv_max, adv)
        hmtx += struct.pack(">Hh", adv, box[0])
        if pts:
            boxes.append(box)
        maxpts, maxcont = max(maxpts, npts), max(maxcont, len(pts))
    xmin = min(b[0] for b in boxes); ymin = min(b[1] for b in boxes)
    xmax = max(b[2] for b in boxes); ymax = max(b[3] for b in boxes)
    n = len(glyphs)

    head = struct.pack(">IIIIHHqqhhhhHHhhh", 0x00010000, 0x00010000, 0, 0x5F0F3CF5, 0x0009, UPM,
                       0, 0, xmin, ymin, xmax, ymax, 0, 8, 2, 1, 0)
    hhea = struct.pack(">IhhhHhhhhhhhhhhhH", 0x00010000, ASC, DESC, 0, adv_max, 0, 0, xmax,
                       1, 0, 0, 0, 0, 0, 0, 0, n)
    maxp = struct.pack(">IHHHHHHHHHHHHHH", 0x00010000, n, maxpts, maxcont, 0, 0, 2, 0, 0, 0, 0, 0, 0, 0, 0)
    loca_t = b"".join(struct.pack(">I", o) for o in loca)
    post = struct.pack(">IIhhIIIII", 0x00030000, 0, -150, 50, 0, 0, 0, 0, 0)

    # cmap: формат 4, кодовые точки подряд с номерами глифов подряд — один отрезок
    segs, start = [], None
    for gid, ch in enumerate(chars, 1):
        cp = ord(ch)
        if start is not None and cp == prev + 1 and gid == pgid + 1:
            prev, pgid = cp, gid
            continue
        if start is not None:
            segs.append((start, prev, sgid))
        start, prev, sgid, pgid = cp, cp, gid, gid
    segs.append((start, prev, sgid))
    segs.append((0xFFFF, 0xFFFF, 0))
    sc = len(segs)
    sr = 2 * 2 ** int(math.log2(sc))
    ends = b"".join(struct.pack(">H", e) for _, e, _ in segs)
    starts = b"".join(struct.pack(">H", s) for s, _, _ in segs)
    deltas = b"".join(struct.pack(">H", ((g - s) if s != 0xFFFF else 1) & 0xFFFF) for s, _, g in segs)
    ranges = b"\0\0" * sc
    body = struct.pack(">HHHH", 2 * sc, sr, int(math.log2(sr // 2)), 2 * sc - sr) + ends + b"\0\0" + starts + deltas + ranges
    sub = struct.pack(">HHH", 4, 6 + len(body), 0) + body
    cmap = struct.pack(">HH", 0, 2) + struct.pack(">HHI", 0, 3, 20) + struct.pack(">HHI", 3, 1, 20) + sub

    names = {0: "Delta OS. Свободно для любого использования.", 1: "Delta Dots", 2: "Regular",
             3: "Delta Dots Regular 1.0", 4: "Delta Dots", 5: "Version 1.0", 6: "DeltaDots-Regular"}
    recs, strs = b"", b""
    for nid, s in names.items():
        e = s.encode("utf-16-be")
        recs += struct.pack(">HHHHHH", 3, 1, 0x409, nid, len(e), len(strs))
        strs += e
    name = struct.pack(">HHH", 0, len(names), 6 + len(recs)) + recs + strs

    avg = sum(struct.unpack(">H", hmtx[i:i + 2])[0] for i in range(0, len(hmtx), 4)) // n
    cps = [ord(c) for c in chars]
    os2 = struct.pack(">HhHHH", 4, avg, 400, 5, 0)
    os2 += struct.pack(">10h", 650, 600, 0, 75, 650, 600, 0, 350, 50, 350)
    os2 += struct.pack(">h", 0) + bytes([2, 0, 6, 9, 0, 0, 0, 0, 0, 0])
    os2 += struct.pack(">IIII", (1 << 0) | (1 << 1) | (1 << 9) | (1 << 31), 0, 0, 0)
    os2 += b"DLTA" + struct.pack(">HHH", 0x40, min(cps), min(max(cps), 0xFFFF))
    os2 += struct.pack(">hhhHH", ASC, DESC, 0, max(ASC, ymax), max(-DESC, -ymin))
    os2 += struct.pack(">II", (1 << 0) | (1 << 2), 0)
    os2 += struct.pack(">hhHHH", 5 * CELL, 7 * CELL, 0, 32, 1)

    tables = {b"OS/2": os2, b"cmap": cmap, b"glyf": glyf, b"head": head, b"hhea": hhea,
              b"hmtx": hmtx, b"loca": loca_t, b"maxp": maxp, b"name": name, b"post": post}
    tags = sorted(tables)
    nt = len(tags)
    es = int(math.log2(nt))
    out = struct.pack(">IHHHH", 0x00010000, nt, 16 * 2 ** es, es, 16 * nt - 16 * 2 ** es)
    off = 12 + 16 * nt
    dirs, blob = b"", b""
    for t in tags:
        d = tables[t]
        dirs += struct.pack(">4sIII", t, checksum(d), off + len(blob), len(d))
        blob += d + b"\0" * (-len(d) % 4)
    font = bytearray(out + dirs + blob)
    adj = (0xB1B0AFBA - checksum(bytes(font))) & 0xFFFFFFFF
    hoff = off + sum(len(tables[t]) + (-len(tables[t]) % 4) for t in tags[:tags.index(b"head")])
    font[hoff + 8:hoff + 12] = struct.pack(">I", adj)
    return bytes(font)


